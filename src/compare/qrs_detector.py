    '''
    final_rpeaks, rpeaks, signal_processed  = get_final_rpeaks(signal, sampling_rate = 500, corr_threshold = 0.9)
    
    R peaks for dominant class
    
    Inputs:
        signal (numpy array): single-lead ECG. 
        sampling_rate (float): the sampling frequency of the ECG.  
        corr_threshold (float): threshold of the correlation between QRS complexes (between 0 and 1). 
        
    Output:
        final_rpeaks (list): list containing the positions of the R peaks after removing beats from the non-dominant class.
        
        rpeaks (list): list containing the positions of the R peaks before removing beats from the non-dominant class.
    '''   
    corrected_signal, filtered_signal, baseline = baseline_correction(signal)
    
    rpeaks = find_rpeaks(np.array(corrected_signal), sampling_rate = sampling_rate)
    
