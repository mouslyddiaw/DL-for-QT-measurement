def create_template(signal, rpeaks, final_rpeaks, sampling_rate = 500, len_template = 1200, position_rpeak = 400, show = False):  
    '''
    template = create_template(signal_processed, final_rpeaks, sampling_rate = 500, len_template = 1200, position_rpeak = 400, show = False)
    
    Creates a representative beat (template) for the input ECG.
    
    Inputs:
        signal (numpy array): single-lead ECG. 
        final_rpeaks (list): list containing the positions of the R peaks after removing beats from the non-dominant class.
        sampling_rate (float): the sampling frequency of the ECG. 
        len_template (int): desired length of the template in msec.
        position_rpeak (int): desired position of the R peak in msec. 
        show (boolean): if True displays the ECG signal with R peak positions and the resulting template
        
    Output:
        template (numpy array): template generated by averaging beats from the dominant class. 
    ''' 
    len_template_in_samples = int(convert_from_msec_to_samples(len_template, sampling_rate))
    position_rpeak_in_samples = int(convert_from_msec_to_samples(position_rpeak, sampling_rate))  
    
    corrected_signal, filtered_signal, baseline = baseline_correction(signal)
   
    dominant_beats = [ filtered_signal[k - position_rpeak_in_samples : k - position_rpeak_in_samples + len_template_in_samples] \
                       for k in final_rpeaks if (k - position_rpeak_in_samples > 0) \
                       and ( k - position_rpeak_in_samples + len_template_in_samples < len(filtered_signal) )]
    #for beat in dominant_beats:
    #    plt.plot(beat)
    #plt.show()
    
    template = list(_average(dominant_beats))  
    if show:
        #R peak detection
        time = [convert_from_samples_to_sec(i, sampling_rate, milli=False) for i in range(len(filtered_signal))]
        plt.figure(figsize = (16, 5))
        plt.title('Final R peaks (black), removed R peaks (red)')
        plt.plot(time, signal)
        plt.plot(time, np.array(corrected_signal))
        for peak in rpeaks: 
            if peak in final_rpeaks:
                plt.axvline(convert_from_samples_to_sec(peak, sampling_rate, milli=False), ls ='--', color='k')
            else:
                plt.axvline(convert_from_samples_to_sec(peak, sampling_rate, milli=False), ls ='--', color='tab:red') 
        plt.xlabel('Time (s)')
        plt.ylabel('Amplitude')
        plt.show() 
        
        #Template creation
        time = [convert_from_samples_to_sec(i, sampling_rate, milli=True) for i in range(len_template_in_samples)]
        plt.title('Average beat')
        plt.plot(time, template)
        plt.xlabel('Time (ms)')
        plt.ylabel('Amplitude')
        plt.show() 
    return template 

